import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { generateSkillReferences, loadGuidance, type GuidanceSnapshot } from "@codecaine-ai/prompt-kit-server";
import { PACKAGE_ROOT } from "./lifecycle";

export {
	generateSkillReferences,
	loadGuidance,
	type GuidanceSnapshot,
	type GuidanceSource,
} from "@codecaine-ai/prompt-kit-server";

const REPOSITORY_ROOT = resolve(PACKAGE_ROOT, "../..");
const EDITOR_CATALOG = "packages/prompt-kit-agent/catalog/prompt-editor";

/**
 * Prompt-editor sources the skill carries beyond the authoring guidance.
 * Each `output` is a generated file under the skill folder. The system prompt
 * has no output: SKILL.md's "Work Requests" section is its hand-adapted form,
 * and its hash in snapshot.json shows when that section needs review.
 */
export const SKILL_SOURCES: readonly { path: string; output?: string }[] = [
	{ path: `${EDITOR_CATALOG}/context/blocks/10-state-reference.md`, output: "references/prompt-state-reference.md" },
	{ path: `${EDITOR_CATALOG}/context/blocks/20-tool-guide.md`, output: "references/prompt-tool-guide.md" },
	{ path: `${EDITOR_CATALOG}/prompt/prompt.json` },
];

const sha256 = (content: string) => createHash("sha256").update(content).digest("hex");

/**
 * Write the whole skill folder beside SKILL.md: the authoring references and
 * snapshot.json from `generateSkillReferences`, the prompt-editor references,
 * and a `skillSources` entry in snapshot.json that hashes each editor source.
 * Deterministic, so a second run changes nothing.
 */
export async function generateSkillFolder(
	outputDir: string,
	guidance?: GuidanceSnapshot,
	repositoryRoot = REPOSITORY_ROOT,
): Promise<void> {
	await generateSkillReferences(outputDir, guidance);
	const skillSources = await Promise.all(
		SKILL_SOURCES.map(async (source) => {
			const content = await readFile(join(repositoryRoot, source.path), "utf8");
			const hash = sha256(content);
			if (source.output) {
				const stamp = `<!-- Generated by prompt-kit-mcp from ${source.path} (sha256 ${hash}). Regenerate with \`bun packages/prompt-kit-mcp/src/cli.ts guidance --write\`. -->\n`;
				await writeFile(join(outputDir, source.output), `${stamp}${content}`);
			}
			return { path: source.path, sha256: hash, ...(source.output ? { output: source.output } : {}) };
		}),
	);
	const snapshotFile = join(outputDir, "snapshot.json");
	const snapshot = JSON.parse(await readFile(snapshotFile, "utf8")) as Record<string, unknown>;
	await writeFile(snapshotFile, `${JSON.stringify({ ...snapshot, skillSources }, null, 2)}\n`);
}
