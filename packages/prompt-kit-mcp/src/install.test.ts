import { afterEach, describe, expect, test } from "bun:test";
import { mkdtemp, mkdir, readFile, readdir, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { claudeConfig, codexConfig, doctorClients, installClients, restoreInstallation } from "./install";

const dirs: string[] = [];
async function fixture() {
  const homeDir = await mkdtemp(join(tmpdir(), "docs-install-test-"));
  dirs.push(homeDir);
  return { homeDir, packageRoot: "/checkout with spaces/prompt-kit-mcp", bunPath: "/bin/bun" };
}
const SNAPSHOT_ID = `sha256:${"a".repeat(64)}`;
const SNAPSHOT = JSON.stringify({ schemaVersion: 1, snapshotId: SNAPSHOT_ID, profile: "generic", sources: [] });
/** The first line of each reference the old server generator wrote, as the stale copy on command-center holds it. */
const stamp = (id = SNAPSHOT_ID) => `<!-- Generated by @codecaine-ai/prompt-kit-server guidance; snapshot ${id}. Refresh the installation to regenerate. -->\n`;
/** A skill copy as an earlier install wrote it, under `root` in the test home, with `extra` files beside the generator's. */
async function oldCopy(home: string, root: string, name: string, extra: Record<string, string> = {}) {
  const dir = join(home, root, name);
  const files = { "SKILL.md": `---\nname: ${name}\ndescription: Old.\n---\nOld rules.\n`, "snapshot.json": SNAPSHOT,
    "references/standards.md": `${stamp()}Old standards\n`, "references/catalog.md": `${stamp()}Old catalog\n`, "references/details/quality.md": `${stamp()}Old quality\n`, ...extra };
  for (const [file, text] of Object.entries(files)) {
    await mkdir(join(dir, file, ".."), { recursive: true });
    await writeFile(join(dir, file), text);
  }
  return dir;
}
afterEach(async () => { await Promise.all(dirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true }))); });

describe("client installation", () => {
  test("preview creates no user files and includes all three clients", async () => {
    const options = await fixture();
    const result = await installClients(options);
    expect(result.mode).toBe("preview");
    expect(result.clients).toEqual(["codex", "claude", "pi"]);
    expect(result.changes.every((change) => change.action === "create" && !change.written)).toBe(true);
    expect(await readdir(options.homeDir)).toEqual([]);
    expect(result.command.args).toEqual(["/checkout with spaces/prompt-kit-mcp/src/cli.ts", "mcp"]);
  });
  test("preserves user settings, creates backups, and reinstalls without changes", async () => {
    const options = await fixture();
    await mkdir(join(options.homeDir, ".codex"));
    const originalToml = '# keep my comment\nmodel = "my-model"\n[mcp_servers.other]\ncommand = "other"\n';
    const originalClaude = JSON.stringify({ theme: "dark", mcpServers: { other: { type: "stdio", command: "other" } }, projects: { "/work": { trusted: true } } });
    await writeFile(join(options.homeDir, ".codex/config.toml"), originalToml);
    await writeFile(join(options.homeDir, ".claude.json"), originalClaude);
    const result = await installClients({ ...options, write: true });
    const codex = await readFile(join(options.homeDir, ".codex/config.toml"), "utf8");
    expect(codex.startsWith(originalToml)).toBe(true);
    expect((Bun.TOML.parse(codex) as Record<string, unknown>).mcp_servers).toMatchObject({ other: { command: "other" }, "prompt-kit": { command: "/bin/bun" } });
    const claude = JSON.parse(await readFile(join(options.homeDir, ".claude.json"), "utf8"));
    expect(claude).toMatchObject({ theme: "dark", mcpServers: { other: { command: "other" }, "prompt-kit": { type: "stdio", command: "/bin/bun" } } });
    expect(claude.mcpServers["prompt-kit"].args).not.toContain("--workspace");
    for (const change of result.changes.filter((entry) => entry.backup)) {
      expect(await readFile(change.backup!, "utf8")).toBe(change.path.endsWith("toml") ? originalToml : originalClaude);
    }
    const repeat = await installClients({ ...options, write: true });
    expect(repeat.changes.every((change) => change.action === "unchanged" && !change.written)).toBe(true);
    expect((await doctorClients(options)).ok).toBe(true);
    const pi = await readFile(join(options.homeDir, ".pi/agent/extensions/prompt-kit.ts"), "utf8");
    expect(pi).toContain("createPiExtension");
  });
  test("invalid existing config aborts before any install writes", async () => {
    const options = await fixture();
    await writeFile(join(options.homeDir, ".claude.json"), "broken JSON");
    await expect(installClients({ ...options, write: true })).rejects.toThrow();
    expect(await readdir(options.homeDir)).toEqual([".claude.json"]);
  });
  test("rolls back earlier commits when a later destination fails", async () => {
    const options = await fixture();
    await mkdir(join(options.homeDir, ".codex"));
    const originalCodex = 'model = "keep"\n';
    const originalClaude = '{"theme":"keep"}\n';
    await writeFile(join(options.homeDir, ".codex/config.toml"), originalCodex);
    await writeFile(join(options.homeDir, ".claude.json"), originalClaude);
    await expect(installClients({ ...options, write: true, testFault: (_phase, _path, index) => {
      if (index === 1) throw new Error("injected commit failure");
    } })).rejects.toThrow("injected commit failure");
    expect(await readFile(join(options.homeDir, ".codex/config.toml"), "utf8")).toBe(originalCodex);
    expect(await readFile(join(options.homeDir, ".claude.json"), "utf8")).toBe(originalClaude);
    const leftovers = [...new Bun.Glob("**/*codecaine-*").scanSync({ cwd: options.homeDir, onlyFiles: true })];
    expect(leftovers).toEqual([]);
  });
  test("individual clients install only their bindings, and no skill; doctor reports a changed binding", async () => {
    const options = await fixture();
    await installClients({ ...options, clients: ["pi"], write: true });
    expect(await readdir(options.homeDir)).toEqual([".pi"]);
    await writeFile(join(options.homeDir, ".pi/agent/extensions/prompt-kit.ts"), "// edited\n");
    const result = await doctorClients({ ...options, clients: ["pi"] });
    expect(result.ok).toBe(false);
    expect(result.checks.filter((check) => check.status === "outdated")).toHaveLength(1);
  });
  test("does not overwrite unmanaged or customized Codex server entries", () => {
    expect(() => codexConfig('[mcp_servers.prompt-kit]\ncommand = "custom"\n', "bun", [])).toThrow("unmanaged");
    const managed = codexConfig("", "bun", []).replace("tool_timeout_sec = 120", 'tool_timeout_sec = 120\nenabled = false');
    expect(() => codexConfig(managed, "bun", [])).toThrow("custom fields");
  });
  test("refuses unmanaged Claude collisions and marks installer-owned entries", () => {
    for (const entry of [
      { type: "http", url: "https://example.com/mcp" },
      { type: "stdio", command: "custom", args: [] },
    ]) expect(() => claudeConfig(JSON.stringify({ mcpServers: { "prompt-kit": entry } }), "bun", ["cli.ts", "mcp"])).toThrow("unmanaged");
    const installed = claudeConfig(null, "bun", ["cli.ts", "mcp"]);
    expect(JSON.parse(installed).mcpServers["prompt-kit"].env.CODECAINE_PROMPTS_INSTALLER).toBe("prompt-kit-mcp/v1");
    expect(() => claudeConfig(installed, "new-bun", ["new-cli.ts", "mcp"])).not.toThrow();
  });
  test("migrates the legacy Codex block and keeps unmanaged legacy entries", () => {
    const legacy = 'model = "keep"\n\n# BEGIN CODECAINE PROMPTS MCP (managed by prompt-kit-mcp install)\n[mcp_servers.codecaine-prompts]\ncommand = "bun"\nargs = []\n# END CODECAINE PROMPTS MCP\n';
    const migrated = codexConfig(legacy, "bun", []);
    expect(migrated).not.toContain("CODECAINE PROMPTS");
    expect(Object.keys((Bun.TOML.parse(migrated) as any).mcp_servers)).toEqual(["prompt-kit"]);
    expect(codexConfig(migrated, "bun", [])).toBe(migrated);
    const unmanaged = '[mcp_servers.codecaine-prompts]\ncommand = "custom"\n';
    expect(Object.keys((Bun.TOML.parse(codexConfig(unmanaged, "bun", [])) as any).mcp_servers)).toEqual(["codecaine-prompts", "prompt-kit"]);
  });
  test("migrates only the installer-owned legacy Claude entry", () => {
    const legacy = JSON.parse(claudeConfig(null, "bun", ["cli.ts", "mcp"]).replace('"prompt-kit"', '"codecaine-prompts"'));
    legacy.mcpServers["codecaine-prompts"].timeout = 5;
    const migrated = JSON.parse(claudeConfig(JSON.stringify(legacy), "bun", ["cli.ts", "mcp"]));
    expect(Object.keys(migrated.mcpServers)).toEqual(["prompt-kit"]);
    expect(migrated.mcpServers["prompt-kit"].timeout).toBe(5);
    const unmanaged = { mcpServers: { "codecaine-prompts": { type: "stdio", command: "custom", args: [] } } };
    expect(JSON.parse(claudeConfig(JSON.stringify(unmanaged), "bun", [])).mcpServers["codecaine-prompts"]).toEqual(unmanaged.mcpServers["codecaine-prompts"]);
  });
  test("retires the skill copies earlier installs wrote, keeps a user's file and the backups, and restore brings them back", async () => {
    const options = await fixture();
    const current = await oldCopy(options.homeDir, ".agents/skills", "prompt-kit", { "references/mine.md": "Mine\n", "references/details/editor-tool-guide.md": `${stamp()}Old tools\n` });
    const legacy = await oldCopy(options.homeDir, ".claude/skills", "codecaine-prompts", { "SKILL.md.codecaine-backup-1-x": "Older\n" });
    await mkdir(join(options.homeDir, ".pi/agent/extensions"), { recursive: true });
    const legacyBridge = join(options.homeDir, ".pi/agent/extensions/codecaine-prompts.ts");
    await writeFile(legacyBridge, "// Managed by Codecaine Prompts. Re-run install to update this checkout path.\n");
    const report = await installClients({ ...options, write: true });
    const removed = report.changes.filter((change) => change.action === "remove");
    const inCopy = (dir: string) => removed.filter((change) => change.path.startsWith(`${dir}/`)).map((change) => change.path.slice(dir.length + 1));
    // Generator files only, references first and the owner markers snapshot.json and SKILL.md last.
    expect(inCopy(current)).toEqual(["references/standards.md", "references/catalog.md", "references/details/quality.md", "references/details/editor-tool-guide.md", "snapshot.json", "SKILL.md"]);
    expect(inCopy(legacy)).toEqual(["references/standards.md", "references/catalog.md", "references/details/quality.md", "snapshot.json", "SKILL.md"]);
    expect(removed.filter((change) => change.kind === "skill")).toHaveLength(11);
    expect(removed.every((change) => change.written && change.backup)).toBe(true);
    expect(await readFile(join(current, "references/mine.md"), "utf8")).toBe("Mine\n");
    expect(await readFile(join(legacy, "SKILL.md.codecaine-backup-1-x"), "utf8")).toBe("Older\n");
    for (const dir of [current, legacy]) expect([...new Bun.Glob("**/*").scanSync({ cwd: dir, onlyFiles: true })].filter((file) => !file.includes(".codecaine-backup-")).sort()).toEqual(dir === current ? ["references/mine.md"] : []);
    await restoreInstallation(report, { write: true });
    expect(await readFile(join(current, "SKILL.md"), "utf8")).toContain("name: prompt-kit");
    expect(await readFile(join(legacy, "references/catalog.md"), "utf8")).toBe(`${stamp()}Old catalog\n`);
    expect(await readFile(legacyBridge, "utf8")).toContain("Codecaine Prompts");
  });
  test("keeps a folder that is not an installed copy: another name, no generator snapshot, or a symlink", async () => {
    const options = await fixture();
    const renamed = await oldCopy(options.homeDir, ".agents/skills", "prompt-kit", { "SKILL.md": "---\nname: something-else\n---\n" });
    const shapeless = await oldCopy(options.homeDir, ".agents/skills", "codecaine-prompts", { "snapshot.json": "{\"mine\":true}" });
    const elsewhere = await oldCopy(options.homeDir, "elsewhere", "prompt-kit");
    await mkdir(join(options.homeDir, ".claude/skills"), { recursive: true });
    await symlink(elsewhere, join(options.homeDir, ".claude/skills", "prompt-kit"));
    await mkdir(join(options.homeDir, ".pi/agent/extensions"), { recursive: true });
    await writeFile(join(options.homeDir, ".pi/agent/extensions/codecaine-prompts.ts"), "// mine\n");
    const report = await installClients({ ...options, write: true });
    expect(report.changes.some((change) => change.action === "remove")).toBe(false);
    for (const dir of [renamed, shapeless, elsewhere]) expect(await readFile(join(dir, "references/standards.md"), "utf8")).toBe(`${stamp()}Old standards\n`);
    expect(await readFile(join(options.homeDir, ".pi/agent/extensions/codecaine-prompts.ts"), "utf8")).toBe("// mine\n");
  });
  test("never enters a symlinked references folder, and skips a skills root that another tool links", async () => {
    const options = await fixture();
    const outside = join(options.homeDir, "outside");
    await mkdir(join(outside, "details"), { recursive: true });
    await writeFile(join(outside, "standards.md"), "Not the installer's\n");
    const copy = await oldCopy(options.homeDir, ".agents/skills", "prompt-kit");
    await rm(join(copy, "references"), { recursive: true });
    await symlink(outside, join(copy, "references"));
    // A config sync owns ~/.claude/skills: it is a link into the sync's own folder.
    const synced = join(options.homeDir, "fleet", "claude");
    await oldCopy(synced, "", "prompt-kit");
    await mkdir(join(options.homeDir, ".claude"), { recursive: true });
    await symlink(synced, join(options.homeDir, ".claude", "skills"));
    const report = await installClients({ ...options, write: true });
    expect(report.changes.filter((change) => change.action === "remove").map((change) => change.path.slice(copy.length + 1))).toEqual(["snapshot.json", "SKILL.md"]);
    expect(await readFile(join(outside, "standards.md"), "utf8")).toBe("Not the installer's\n");
    expect(await readFile(join(synced, "prompt-kit", "SKILL.md"), "utf8")).toContain("name: prompt-kit");
  });
  test("a listed reference name without the generator's stamp, or with another copy's snapshot id, stays and is no leftover", async () => {
    const options = await fixture();
    const copy = await oldCopy(options.homeDir, ".agents/skills", "prompt-kit", {
      // The 11-source generator never wrote these two: a user added them under listed names.
      "references/details/editor-tool-guide.md": "My tool notes\n",
      "references/details/work-requests.md": `${stamp(`sha256:${"b".repeat(64)}`)}Copied from another install\n`,
      // The older prompt-kit-mcp generator stamped the editor references with their source, not a snapshot.
      "references/prompt-state-reference.md": "<!-- Generated by prompt-kit-mcp from packages/prompt-kit-mcp/catalog/prompt-editor/context/blocks/10-state-reference.md (sha256 0f). Regenerate with `bun packages/prompt-kit-mcp/src/cli.ts guidance --write`. -->\n# Prompt Editor State Reference\n",
    });
    const leftovers = (await doctorClients({ ...options, clients: ["pi"] })).checks.filter((check) => check.status === "leftover").map((check) => check.path.slice(copy.length + 1));
    expect(leftovers).toEqual(["references/standards.md", "references/catalog.md", "references/prompt-state-reference.md", "references/details/quality.md", "snapshot.json", "SKILL.md"]);
    await installClients({ ...options, clients: ["pi"], write: true });
    expect(await readFile(join(copy, "references/details/editor-tool-guide.md"), "utf8")).toBe("My tool notes\n");
    expect(await readFile(join(copy, "references/details/work-requests.md"), "utf8")).toContain("Copied from another install");
  });
  test("doctor reports each file of a leftover copy", async () => {
    const options = await fixture();
    await installClients({ ...options, write: true });
    expect((await doctorClients(options)).ok).toBe(true);
    await oldCopy(options.homeDir, ".agents/skills", "prompt-kit");
    const result = await doctorClients(options);
    expect(result.ok).toBe(false);
    expect(result.checks.filter((check) => check.status === "leftover").map((check) => check.path.split("/").slice(-2).join("/"))).toEqual(
      ["references/standards.md", "references/catalog.md", "details/quality.md", "prompt-kit/snapshot.json", "prompt-kit/SKILL.md"]);
  });
  test("restore previews, restores exact old configuration, and refuses later edits", async () => {
    const options = await fixture();
    const original = '{"theme":"dark"}\n';
    await writeFile(join(options.homeDir, ".claude.json"), original);
    const report = await installClients({ ...options, clients: ["claude"], write: true });
    const generated = await readFile(join(options.homeDir, ".claude.json"), "utf8");
    const preview = await restoreInstallation(report);
    expect(preview.changes.every((item) => !item.written)).toBe(true);
    await writeFile(join(options.homeDir, ".claude.json"), "changed by user");
    await expect(restoreInstallation(report, { write: true })).rejects.toThrow("installed file changed");
    const current = report.changes.find((item) => item.path.endsWith(".claude.json"))!;
    await writeFile(current.path, generated);
    await restoreInstallation(report, { write: true });
    expect(await readFile(current.path, "utf8")).toBe(original);
  });
});
